import { afterEach, expect, it, vi } from 'vitest';
import { HarnessStore } from '../store';
import { DshAdapter } from './adapter';
import { DEFAULT_APP_CONFIG } from '../../../shared/config';
import type { HarnessInput } from '../contracts';
const stores: HarnessStore[] = [];
afterEach(() => stores.splice(0).forEach(s => s.close()));
it.each([false, true])('preserves the execution failure and attempts every cleanup even when release fails (cancelled=%s)', async cancelled => {
    const store = new HarnessStore(':memory:'); stores.push(store);
    const abort = new AbortController();
    const input: HarnessInput = { requestId: 'r', attemptId: 'a', characterId: 'c', sessionId: 's', config: DEFAULT_APP_CONFIG, configVersion: 'v', snapshotFingerprint: 'f', systemPrompt: '', messages: [{ role: 'user', content: 'hi' }], signal: abort.signal, assertContext: async () => {} };
    const lease = { run: async () => { if (cancelled) abort.abort(); throw new Error('original provider failure'); }, flush: async () => true, release: vi.fn(async () => { throw new Error('dispose timeout'); }), cancel: async () => {} };
    const cancelActions = vi.fn(async () => { throw new Error('card cleanup failure'); });
    const cleanup = vi.fn(async () => { throw new Error('log cleanup failure'); });
    const adapter = new DshAdapter({ acquire: async () => lease }, store, cancelActions, cleanup);
    const result = await adapter.run(input, () => {});
    expect(result).toMatchObject({ state: cancelled ? 'cancelled' : 'failed' });
    if (result.state === 'completed') throw new Error('Failed execution was reported complete');
    expect(result.error).toContain('original provider failure');
    expect(result.error).toContain('dispose timeout');
    expect(result.error).toContain('log cleanup failure');
    if (cancelled) expect(result.error).toContain('card cleanup failure');
    expect(lease.release).toHaveBeenCalledOnce();
    expect(cleanup).toHaveBeenCalledOnce();
    expect(store.get(input)).toMatchObject({ deliverySuppressed: true, cleanupPending: true });
});
it('records a durable completion and rejects re-execution of an existing attempt', async () => {
    const store = new HarnessStore(':memory:');
    stores.push(store);
    const input: HarnessInput = { requestId: 'r', attemptId: 'a', characterId: 'c', sessionId: 's', config: DEFAULT_APP_CONFIG, configVersion: 'v', snapshotFingerprint: 'f', systemPrompt: '', messages: [{ role: 'user', content: 'hi' }], signal: new AbortController().signal, assertContext: async () => { } };
    const lease = { run: vi.fn(async () => ({ state: 'completed' as const, text: 'saved' })), flush: vi.fn(async () => true), release: vi.fn(), cancel: vi.fn() };
    const adapter = new DshAdapter({ acquire: async () => lease }, store);
    const result = await adapter.run(input, () => { });
    expect(result).toMatchObject({ state: 'completed', text: 'saved', source: { attemptId: 'a', messageId: store.get(input)!.messageId } });
    expect(store.get(input)).toMatchObject({ state: 'completed', durable: true, dshSessionId: 'a' });
    expect(await adapter.run(input, () => { })).toMatchObject({ state: 'interrupted' });
    expect(lease.run).toHaveBeenCalledTimes(1);
    expect(lease.release).toHaveBeenCalledTimes(1);
});
it.each(['abort', 'context'])('does not publish or recover a completion invalidated during final flush: %s', async mode => {
    const store = new HarnessStore(':memory:'); stores.push(store);
    const abort = new AbortController(); let stale = false;
    const input: HarnessInput = { requestId:'r', attemptId:'a', characterId:'c', sessionId:'s', config:DEFAULT_APP_CONFIG, configVersion:'v', snapshotFingerprint:'f', systemPrompt:'', messages:[{role:'user',content:'hi'}], signal:abort.signal, assertContext:async()=>{if(stale)throw new Error('stale context')} };
    const lease = {run:async()=>({state:'completed' as const,text:'invalid reply'}),flush:async()=>{if(mode==='abort')abort.abort();else stale=true;return true},release:async()=>{},cancel:async()=>{}};
    const adapter = new DshAdapter({acquire:async()=>lease},store);
    expect((await adapter.run(input,()=>{})).state).toBe(mode==='abort'?'cancelled':'failed');
    expect(store.get(input)!.state).not.toBe('completed');
});
